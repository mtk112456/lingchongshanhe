#requires -Version 5.1
<#
.SYNOPSIS
  Qingzhu slice acceptance watcher. Runs checks and writes a JSON result.

.DESCRIPTION
  Every 30 minutes (or once with -Once) this script:
    - fingerprints source/assets/config so unchanged runs are skipped
    - runs PHP backend acceptance (14 cases)
    - runs Godot ClientSmoke and ReplaySmoke
    - runs the full-resolution screenshot suite
    - probes screenshots for blank panels and validates GPT assets
    - checks whether the APK is older than client source
  The Chinese STATUS.md is generated by tools/watch_report.py from the JSON.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\watch_acceptance.ps1 -Once -Force
#>
[CmdletBinding()]
param(
    [string]$Root = '',
    [int]$IntervalMinutes = 30,
    [switch]$Once,
    [switch]$Force,
    [switch]$SkipCapture,
    [switch]$SkipResetDb
)

$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'
try {
    [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false)
    $OutputEncoding = New-Object System.Text.UTF8Encoding($false)
} catch { }

if ([string]::IsNullOrWhiteSpace($Root)) {
    if (-not [string]::IsNullOrWhiteSpace($PSScriptRoot)) {
        $Root = Split-Path -Parent $PSScriptRoot
    } else {
        $Root = (Get-Location).Path
    }
}
$Root = (Resolve-Path -LiteralPath $Root).Path

$WatchDir      = Join-Path $Root 'tools\watch'
$LogDir        = Join-Path $WatchDir 'logs'
$StatePath     = Join-Path $WatchDir 'state.json'
$ResultPath    = Join-Path $WatchDir 'run_result.json'
$HeartbeatPath = Join-Path $WatchDir 'HEARTBEAT.txt'
$HistoryPath   = Join-Path $WatchDir 'history.jsonl'
$ProbePath     = Join-Path $WatchDir 'probe.json'

$Client    = Join-Path $Root 'client'
$Server    = Join-Path $Root 'server\slice'
$Screens   = Join-Path $Client 'tests'
$Apk       = Join-Path $Client 'build\android\qingzhu_slice.apk'
$Godot     = Join-Path $Root 'tools\Godot_v4.7.2-stable\Godot_v4.7.2-stable_win64.exe'
$Probe     = Join-Path $Root 'tools\watch_probe.py'
$Reporter  = Join-Path $Root 'tools\watch_report.py'
$Php       = (Get-Command php -ErrorAction SilentlyContinue).Source
$PhpDir    = if ($Php) { Split-Path $Php -Parent } else { '' }
$Python    = (Get-Command python -ErrorAction SilentlyContinue).Source
$StatusPath = Join-Path $WatchDir 'STATUS.md'
$FailMsgPath = Join-Path $WatchDir 'FAIL_MESSAGE_ANTIGRAVITY.txt'
$ReadyMsgPath = Join-Path $WatchDir 'READY_TO_MERGE.txt'
$ContactPath = Join-Path $WatchDir 'contact_latest.jpg'

New-Item -ItemType Directory -Force -Path $WatchDir, $LogDir | Out-Null

$script:CurrentLog = $null

function Write-Log {
    param([string]$Text)
    $line = '[{0}] {1}' -f (Get-Date -Format 'HH:mm:ss'), $Text
    if ($script:CurrentLog) {
        Add-Content -LiteralPath $script:CurrentLog -Value $line -Encoding UTF8
    }
    Write-Host $line
}

function Read-State {
    if (-not (Test-Path -LiteralPath $StatePath)) { return $null }
    try {
        return (Get-Content -LiteralPath $StatePath -Raw -Encoding UTF8 | ConvertFrom-Json)
    } catch {
        return $null
    }
}

function Write-Utf8Json {
    param([string]$Path, $Value)
    $json = $Value | ConvertTo-Json -Depth 12
    $utf8 = New-Object System.Text.UTF8Encoding($true)
    [System.IO.File]::WriteAllText($Path, $json, $utf8)
}

function Get-DirtyStatus {
    if (-not (Test-Path -LiteralPath (Join-Path $Root '.git'))) { return @() }
    $raw = @(& git -C $Root status --porcelain --untracked-files=all 2>$null)
    return @($raw | Where-Object {
        $_ -notmatch 'client/tests/screenshot_' -and
        $_ -notmatch 'client/tests/screenshots_contact' -and
        $_ -notmatch 'tools/watch/' -and
        $_ -notmatch 'art_src/gpt/.*\.preview\.jpg' -and
        $_ -notmatch '\.import$'
    })
}

function Get-Fingerprint {
    $files = New-Object System.Collections.Generic.List[string]

    if (Test-Path -LiteralPath $Client) {
        Get-ChildItem -LiteralPath $Client -File -Recurse -ErrorAction SilentlyContinue |
            Where-Object {
                $_.FullName -notmatch '\\build\\' -and
                $_.FullName -notmatch '\\\.godot\\' -and
                $_.FullName -notmatch '\\tests\\screenshot_' -and
                $_.FullName -notmatch '\\tests\\screenshots_contact' -and
                $_.FullName -notmatch '\.import$'
            } |
            ForEach-Object { $files.Add($_.FullName) }
    }

    $gpt = Join-Path $Root 'art_src\gpt'
    if (Test-Path -LiteralPath $gpt) {
        Get-ChildItem -LiteralPath $gpt -File -ErrorAction SilentlyContinue |
            Where-Object { $_.Extension -in '.png', '.md', '.json' } |
            ForEach-Object { $files.Add($_.FullName) }
        Get-ChildItem -LiteralPath $gpt -Directory -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -like 'assets_c*' } |
            ForEach-Object {
                Get-ChildItem -LiteralPath $_.FullName -File -ErrorAction SilentlyContinue |
                    ForEach-Object { $files.Add($_.FullName) }
            }
    }

    foreach ($sub in @('src', 'public', 'tests', 'migrations')) {
        $p = Join-Path $Server $sub
        if (Test-Path -LiteralPath $p) {
            Get-ChildItem -LiteralPath $p -File -Recurse -ErrorAction SilentlyContinue |
                Where-Object { $_.Extension -in '.php', '.sql', '.html', '.md' } |
                ForEach-Object { $files.Add($_.FullName) }
        }
    }
    foreach ($name in @('schema.sql', 'legacy_schema.sql', 'seed.sql', 'legacy_seed.sql', 'bootstrap.php', 'README.md')) {
        $p = Join-Path $Server $name
        if (Test-Path -LiteralPath $p) { $files.Add($p) }
    }

    $teacherWeb = Join-Path $Root 'deploy\teacher-web'
    if (Test-Path -LiteralPath $teacherWeb) {
        Get-ChildItem -LiteralPath $teacherWeb -File -ErrorAction SilentlyContinue |
            ForEach-Object { $files.Add($_.FullName) }
    }

    Get-ChildItem -LiteralPath $Root -File -Filter '*.md' -ErrorAction SilentlyContinue |
        ForEach-Object { $files.Add($_.FullName) }

    $files.Add($Apk)

    $sigs = foreach ($f in ($files | Sort-Object -Unique)) {
        $item = Get-Item -LiteralPath $f -ErrorAction SilentlyContinue
        if ($null -eq $item) {
            "$f|missing"
        } else {
            "$f|$($item.Length)|$($item.LastWriteTimeUtc.Ticks)"
        }
    }

    $head = ''
    if (Test-Path -LiteralPath (Join-Path $Root '.git')) {
        $head = (& git -C $Root rev-parse HEAD 2>$null | Select-Object -First 1)
    }
    $dirty = Get-DirtyStatus
    $payload = ($sigs -join "`n") + "`nHEAD=$head`nSTATUS=$($dirty -join "`n")"

    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $bytes = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($payload))
        return (-join ($bytes | ForEach-Object { $_.ToString('x2') }))
    } finally {
        $sha.Dispose()
    }
}

function ConvertTo-ArgString {
    param([string[]]$Arguments)
    $quoted = foreach ($arg in $Arguments) {
        if ($arg -match '[\s"]') {
            '"' + ($arg -replace '"', '\"') + '"'
        } else {
            $arg
        }
    }
    return ($quoted -join ' ')
}

function Invoke-ProcessWithTimeout {
    param(
        [string]$Exe,
        [string[]]$Arguments,
        [int]$TimeoutSeconds,
        [string]$Name,
        [string]$Stamp
    )
    $outPath = Join-Path $LogDir ("{0}.{1}.out.txt" -f $Name, $Stamp)
    $errPath = Join-Path $LogDir ("{0}.{1}.err.txt" -f $Name, $Stamp)

    # Windows PowerShell 5.1: Start-Process -PassThru + redirection does not
    # reliably fill ExitCode, so use the .NET Process API directly.
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $Exe
    $psi.Arguments = ConvertTo-ArgString $Arguments
    $psi.UseShellExecute = $false
    $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.StandardOutputEncoding = [System.Text.Encoding]::UTF8
    $psi.StandardErrorEncoding = [System.Text.Encoding]::UTF8

    $p = New-Object System.Diagnostics.Process
    $p.StartInfo = $psi
    try {
        $p.Start() | Out-Null
    } catch {
        return [pscustomobject]@{
            ExitCode = 127; TimedOut = $false; Out = ''; Err = $_.Exception.Message
            OutPath = $outPath; ErrPath = $errPath; Started = $false
        }
    }

    $outTask = $p.StandardOutput.ReadToEndAsync()
    $errTask = $p.StandardError.ReadToEndAsync()
    $finished = $p.WaitForExit($TimeoutSeconds * 1000)
    if (-not $finished) {
        try { $p.Kill() } catch { }
        try { $p.WaitForExit(5000) | Out-Null } catch { }
        $exitCode = 124
        $timedOut = $true
    } else {
        $exitCode = $p.ExitCode
        $timedOut = $false
    }

    try { $out = $outTask.Result } catch { $out = '' }
    try { $err = $errTask.Result } catch { $err = '' }
    try {
        $utf8 = New-Object System.Text.UTF8Encoding($false)
        [System.IO.File]::WriteAllText($outPath, [string]$out, $utf8)
        [System.IO.File]::WriteAllText($errPath, [string]$err, $utf8)
    } catch { }

    return [pscustomobject]@{
        ExitCode = $exitCode; TimedOut = $timedOut
        Out = [string]$out; Err = [string]$err
        OutPath = $outPath; ErrPath = $errPath; Started = $true
    }
}

function Get-NewestSourceTime {
    $newest = [datetime]::MinValue
    Get-ChildItem -LiteralPath $Client -File -Recurse -ErrorAction SilentlyContinue |
        Where-Object {
            $_.FullName -notmatch '\\build\\' -and
            $_.FullName -notmatch '\\\.godot\\' -and
            $_.FullName -notmatch '\\tests\\screenshot_' -and
            $_.FullName -notmatch '\.import$'
        } |
        ForEach-Object { if ($_.LastWriteTime -gt $newest) { $newest = $_.LastWriteTime } }
    return $newest
}

