    'screenshot_login_keyart.png',
    'screenshot_tablet_s01_map.png',
    'screenshot_tablet_s01_map_zoom_lod.png',
    'screenshot_tablet_s02_drawer.png',
    'screenshot_tablet_s03_order_confirm.png',
    'screenshot_tablet_s04_war_report.png',
    'screenshot_tablet_s05_battle_replay.png',
    'screenshot_tablet_s06_faction.png',
    'screenshot_tablet_s10_season.png',
    'screenshot_phone_portrait_s01_map.png',
