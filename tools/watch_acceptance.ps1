function Invoke-Cycle {
    $cycleStart = Get-Date
    $stamp = $cycleStart.ToString('yyyyMMdd_HHmmss')
    $script:CurrentLog = Join-Path $LogDir ("watch.{0}.log" -f $stamp)
    Write-Log '==== acceptance watch start ===='

    if (-not (Test-Path -LiteralPath $Godot)) {
        Write-Log "Godot not found: $Godot"
        return 'FAIL'
    }
    if (-not $Php) {
        Write-Log 'php not found; cannot run backend acceptance.'
        return 'FAIL'
    }

    $hash = Get-Fingerprint
    $hashShort = $hash.Substring(0, 12)
    $state = Read-State
    $dirty = Get-DirtyStatus

    if (-not $Force -and $state -and $state.hash -eq $hash -and $state.last_status -in @('PASS', 'WARN')) {
        Write-Log "No source change ($hashShort); skip. Last: $($state.last_status)"
        $heartbeat = @(
            "time=$($cycleStart.ToString('yyyy-MM-dd HH:mm:ss'))",
            "status=$($state.last_status)",
            "hash=$hashShort",
            "last_pass=$($state.last_pass)",
            'note=no source change'
        )
        Set-Content -LiteralPath $HeartbeatPath -Value $heartbeat -Encoding UTF8
        $state.last_run = $cycleStart.ToString('s')
        Write-Utf8Json -Path $StatePath -Value $state
        return 'NO_CHANGE'
    }

    $latestPass = if ($state -and $state.last_pass) { [string]$state.last_pass } else { '' }
    Write-Log "fingerprint $hashShort; dirty $($dirty.Count); last pass $latestPass"

    $phpBase = @('-d', "extension_dir=$PhpDir\ext", '-d', 'extension=pdo_mysql')
    $backendPassed = 0
    $backendFailed = 0
    $backendOk = $false
    $smokeOk = $false
    $replayOk = $false
    $captureOk = $false
    $failReasons = New-Object System.Collections.Generic.List[string]

    if (-not $SkipResetDb) {
        $r = Invoke-ProcessWithTimeout -Exe $Php -Arguments ($phpBase + @((Join-Path $Server 'scripts\setup_test_db.php'))) -TimeoutSeconds 90 -Name 'setup_db' -Stamp $stamp
        if ($r.ExitCode -ne 0) {
            $failReasons.Add('test database reset failed')
            Write-Log "test database reset failed: exit=$($r.ExitCode)"
        }
    }

    Write-Log 'backend acceptance...'
    $r = Invoke-ProcessWithTimeout -Exe $Php -Arguments ($phpBase + @((Join-Path $Server 'tests\run.php'))) -TimeoutSeconds 180 -Name 'backend' -Stamp $stamp
    if ($r.Out -match '==\s*Summary:\s*(\d+)\s*passed,\s*(\d+)\s*failed\s*==') {
        $backendPassed = [int]$Matches[1]
        $backendFailed = [int]$Matches[2]
    }
    $backendOk = ($r.ExitCode -eq 0 -and $backendFailed -eq 0 -and $backendPassed -ge 14)
    if (-not $backendOk) {
        $failReasons.Add("backend: $backendPassed passed / $backendFailed failed / exit=$($r.ExitCode)")
    }
    Write-Log "backend: $backendPassed passed, $backendFailed failed"

    if (-not $SkipResetDb) {
        Invoke-ProcessWithTimeout -Exe $Php -Arguments ($phpBase + @((Join-Path $Server 'scripts\setup_test_db.php'))) -TimeoutSeconds 90 -Name 'setup_before_smoke' -Stamp $stamp | Out-Null
    }

    Write-Log 'ClientSmoke...'
    $r = Invoke-ProcessWithTimeout -Exe $Godot -Arguments @('--headless', '--path', $Client, 'res://tests/ClientSmoke.tscn') -TimeoutSeconds 120 -Name 'client_smoke' -Stamp $stamp
    $smokeOk = ($r.ExitCode -eq 0 -and $r.Out -match 'CLIENT_SMOKE PASS')
    if (-not $smokeOk) {
        $failReasons.Add("ClientSmoke failed (exit=$($r.ExitCode))")
    }
    Write-Log "ClientSmoke: $smokeOk"

    if (-not $SkipResetDb) {
        Invoke-ProcessWithTimeout -Exe $Php -Arguments ($phpBase + @((Join-Path $Server 'scripts\setup_test_db.php'))) -TimeoutSeconds 90 -Name 'setup_before_replay' -Stamp $stamp | Out-Null
    }

    Write-Log 'ReplaySmoke...'
    $r = Invoke-ProcessWithTimeout -Exe $Godot -Arguments @('--headless', '--path', $Client, 'res://tests/ReplaySmoke.tscn') -TimeoutSeconds 120 -Name 'replay_smoke' -Stamp $stamp
    $replayOk = ($r.ExitCode -eq 0 -and $r.Out -match 'REPLAY_SMOKE PASS')
    if (-not $replayOk) {
        $failReasons.Add("ReplaySmoke failed (exit=$($r.ExitCode))")
    }
    Write-Log "ReplaySmoke: $replayOk"

    if (-not $SkipCapture) {
        if (-not $SkipResetDb) {
            Invoke-ProcessWithTimeout -Exe $Php -Arguments ($phpBase + @((Join-Path $Server 'scripts\setup_test_db.php'))) -TimeoutSeconds 90 -Name 'setup_before_capture' -Stamp $stamp | Out-Null
        }
        Write-Log 'screenshot suite...'
        $r = Invoke-ProcessWithTimeout -Exe $Godot -Arguments @('--path', $Client, 'res://tests/CaptureScreenshots.tscn') -TimeoutSeconds 180 -Name 'capture' -Stamp $stamp
        $captureOk = ($r.ExitCode -eq 0 -and $r.Out -match 'CAPTURE_SUITE COMPLETE')
        if (-not $captureOk) {
            $failReasons.Add("screenshot suite failed (exit=$($r.ExitCode))")
        }
        Write-Log "screenshot suite: $captureOk"
    } else {
        $captureOk = $true
        Write-Log 'screenshot suite skipped (-SkipCapture)'
    }

    $missing = New-Object System.Collections.Generic.List[string]
    $tooSmall = New-Object System.Collections.Generic.List[string]
    $stale = New-Object System.Collections.Generic.List[string]
    $newestSource = Get-NewestSourceTime
    foreach ($name in $ExpectedScreens) {
        $p = Join-Path $Screens $name
        if (-not (Test-Path -LiteralPath $p)) {
            $missing.Add($name)
            continue
        }
        $item = Get-Item -LiteralPath $p
        if ($item.Length -lt 15000) { $tooSmall.Add($name) }
        if ($SkipCapture -and $newestSource -gt [datetime]::MinValue -and $item.LastWriteTime -lt $newestSource.AddSeconds(-5)) {
            $stale.Add($name)
        }
    }
    if ($missing.Count -gt 0) { $failReasons.Add("missing screenshots: $($missing -join ', ')") }
    if ($tooSmall.Count -gt 0) { $failReasons.Add("screenshots too small: $($tooSmall -join ', ')") }

    $probeJson = $null
    if ($Python) {
        $probeImages = @()
        foreach ($name in $ExpectedScreens) {
            $p = Join-Path $Screens $name
            if (Test-Path -LiteralPath $p) { $probeImages += $p }
        }
        if ($probeImages.Count -gt 0) {
            $probeArgs = @($Probe, '--images') + $probeImages + @('--assets', '--contact', $ContactPath, '--out', $ProbePath)
            $r = Invoke-ProcessWithTimeout -Exe $Python -Arguments $probeArgs -TimeoutSeconds 90 -Name 'probe' -Stamp $stamp
            if (Test-Path -LiteralPath $ProbePath) {
                try {
                    $probeJson = Get-Content -LiteralPath $ProbePath -Raw -Encoding UTF8 | ConvertFrom-Json
                } catch {
                    $failReasons.Add('probe JSON parse failed')
                }
            } else {
                $failReasons.Add('probe produced no result')
            }
        }
    } else {
        $failReasons.Add('python not found; cannot probe screenshots/assets')
    }

    $blankShots = @()
    $contentFail = New-Object System.Collections.Generic.List[string]
    $assetFail = New-Object System.Collections.Generic.List[string]
    if ($probeJson) {
        if ($probeJson.images) {
            $blankShots = @($probeJson.images | Where-Object { $_.blank_like } | ForEach-Object { $_.name })
            foreach ($metric in $probeJson.images) {
                if ($metric.name -eq 'screenshot_tablet_s04_war_report.png' -and $metric.std -lt 7) {
                    $contentFail.Add('S04 report content too low')
                }
                if ($metric.name -eq 'screenshot_tablet_s05_battle_replay.png' -and $metric.std -lt 7) {
                    $contentFail.Add('S05 replay content too low')
                }
            }
        }
        if ($probeJson.assets) {
            foreach ($prop in $probeJson.assets.PSObject.Properties) {
                $name = $prop.Name
                $info = $prop.Value
                if (-not $info.exists) {
                    $assetFail.Add("$name missing")
                    continue
                }
                if ($null -ne $info.ok -and -not $info.ok) {
                    $assetFail.Add("$name spec mismatch")
                }
                if ($null -ne $info.transparent_corners -and -not $info.transparent_corners) {
                    $assetFail.Add("$name corners not transparent")
                }
            }
        }
    }
    if ($blankShots.Count -gt 0) { $failReasons.Add("blank screenshots: $($blankShots -join ', ')") }
    foreach ($reason in $contentFail) { $failReasons.Add($reason) }
    foreach ($reason in $assetFail) { $failReasons.Add($reason) }

    $apkInfo = if (Test-Path -LiteralPath $Apk) { Get-Item -LiteralPath $Apk } else { $null }
    $apkStale = $false
    $apkMb = 0
    $apkTime = ''
    if ($apkInfo) {
        $apkMb = [math]::Round($apkInfo.Length / 1MB, 1)
        $apkTime = $apkInfo.LastWriteTime.ToString('MM-dd HH:mm')
        if ($newestSource -gt [datetime]::MinValue) {
            $apkStale = $apkInfo.LastWriteTime -lt $newestSource.AddSeconds(-5)
        }
    } else {
        $apkStale = $true
    }

    $hashAfter = Get-Fingerprint
    $unstable = ($hashAfter -ne $hash)

    $status = 'PASS'
    if ($failReasons.Count -gt 0) {
        $status = 'FAIL'
    } elseif ($unstable) {
        $status = 'UNSTABLE'
    } elseif ($apkStale -or $stale.Count -gt 0) {
        $status = 'WARN'
    }

    if ($failReasons.Count -eq 0 -and -not $unstable) {
        $lastPass = $cycleStart.ToString('s')
    } elseif ($state -and $state.last_pass) {
        $lastPass = [string]$state.last_pass
    } else {
        $lastPass = ''
    }

    $duration = [math]::Round(((Get-Date) - $cycleStart).TotalSeconds, 1)

    $result = [ordered]@{
        time = $cycleStart.ToString('s')
        status = $status
        hash = $hashShort
        last_pass = $lastPass
        duration_sec = $duration
        backend_ok = $backendOk
        backend_passed = $backendPassed
        backend_failed = $backendFailed
        smoke_ok = $smokeOk
        replay_ok = $replayOk
        capture_ok = $captureOk
        capture_skipped = [bool]$SkipCapture
        missing = @($missing)
        too_small = @($tooSmall)
        stale = @($stale)
        blank = @($blankShots)
        content_fail = @($contentFail)
        asset_fail = @($assetFail)
        fail_reasons = @($failReasons)
        apk_stale = $apkStale
        apk_mb = $apkMb
        apk_time = $apkTime
        dirty = @($dirty)
        unstable = $unstable
        images = @($probeJson.images)
        assets = $probeJson.assets
    }
    Write-Utf8Json -Path $ResultPath -Value $result

    $entry = [ordered]@{
        time = $cycleStart.ToString('s')
        status = $status
        hash = $hashShort
        backend_passed = $backendPassed
        backend_failed = $backendFailed
        smoke = $smokeOk
        replay = $replayOk
        capture = $captureOk
        missing = $missing.Count
        blank = $blankShots.Count
        assets_fail = $assetFail.Count
        apk_stale = $apkStale
        dirty = $dirty.Count
        duration_sec = $duration
    }
    Add-Content -LiteralPath $HistoryPath -Value ($entry | ConvertTo-Json -Compress) -Encoding UTF8

    $newState = [ordered]@{
        hash = $hash
        last_run = $cycleStart.ToString('s')
        last_status = $status
        last_pass = $lastPass
        backend_passed = $backendPassed
        backend_failed = $backendFailed
        smoke = $smokeOk
        replay = $replayOk
        capture = $captureOk
        apk_stale = $apkStale
        dirty = $dirty.Count
    }
    Write-Utf8Json -Path $StatePath -Value $newState

    $heartbeat = @(
        "time=$($cycleStart.ToString('yyyy-MM-dd HH:mm:ss'))",
        "status=$status",
        "hash=$hashShort",
        "last_pass=$lastPass",
        "duration=$duration"
    )
    Set-Content -LiteralPath $HeartbeatPath -Value $heartbeat -Encoding UTF8

    if ($Python -and (Test-Path -LiteralPath $Reporter) -and (Test-Path -LiteralPath $ResultPath)) {
        try {
            & $Python $Reporter --result $ResultPath --status $StatusPath `
                --fail-msg $FailMsgPath --ready-msg $ReadyMsgPath | Out-Null
        } catch {
            Write-Log "report generation failed: $($_.Exception.Message)"
        }
    }

    if ($status -eq 'FAIL') {
        try { [console]::Beep(440, 350); [console]::Beep(330, 450) } catch { }
    } elseif ($status -eq 'PASS') {
        try { [console]::Beep(880, 120) } catch { }
    }

    Write-Log "==== acceptance watch end: $status ===="
    return $status
}

$mutex = New-Object System.Threading.Mutex($false, 'Local\QingzhuAcceptanceWatch')
$acquired = $false
try {
    $acquired = $mutex.WaitOne(0)
    if (-not $acquired) {
        Write-Host 'Another acceptance watch is running; skip this cycle.'
        exit 0
    }
    if ($Once) {
        Invoke-Cycle | Out-Null
    } else {
        Write-Host "Acceptance watch started: every $IntervalMinutes minutes; Ctrl+C to stop."
        while ($true) {
            Invoke-Cycle | Out-Null
            Start-Sleep -Seconds ([math]::Max(60, $IntervalMinutes * 60))
        }
    }
} finally {
    if ($acquired) {
        try { $mutex.ReleaseMutex() } catch { }
    }
    $mutex.Dispose()
}
